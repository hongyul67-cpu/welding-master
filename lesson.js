/* board-pro 의 .bp-fig svg{width:100%} 를 그대로 두면 그림이 세로로 늘어나
   한 화면을 넘긴다. 이 덱의 그림에만 적용되는 규칙을 한 번 심어 높이로 묶는다.
   (공용 뷰어는 고치지 않는다 — 여기서 내 그림만 다스린다.)
   퀴즈까지 열리면 뷰어가 .compact 로 바뀌어 그림 칸이 20vh 로 줄므로 그때는 더 낮춘다. */
var styled = false;
function once() {
  if (styled) return;
  styled = true;
  var st = document.createElement('style');
  st.textContent =
    '#bp-in .bp-fig svg.wm-fig{height:25vh;width:auto;max-width:100%}' +
    '#bp-in.compact .bp-fig svg.wm-fig{height:13vh}';
  document.head.appendChild(st);
}

function panel(html) {
  once();
  var h = String(html)
    .replace(/<div class="figcap">[\s\S]*?<\/div>/g, '')
    .replace(/<svg class="fig"/g, '<svg class="fig wm-fig"');
  return '<div style="background:#f7f9fc;border-radius:12px;padding:2px 10px;width:100%;' +
         'display:flex;align-items:center;justify-content:center;gap:8px;flex-wrap:wrap">' +
         h + '</div>';
}

